#!/usr/bin/env node
// Retro skin end-level crowd (bead tg-wtv.3): the user's hand-drawn 2012
// robots (art/sets/retro-legacy, images/retro/robots/) on the generated
// phosphor-green night backdrop (art/sets/retro-victory-v1,
// images/retro/victory-bg.png). Writes js/skins/retro-robots.js.
//
// The layout is the 2012 one (git show 8a9315e:EndLevelRobots.js: the same
// robots in the same unlock order, x kept), adapted to the current end-level
// scene: the 2012 screen had its text in the top third, so feet stood from
// y 377 to 760; today the result card covers the top centre and the backdrop's
// ground plane starts at its horizon (y 496), so every robot's feet are mapped
// linearly from [377, 760] into [GROUND_TOP, GROUND_BOTTOM] and z follows the
// feet (lower on screen = in front), as tools/art/freed-layout.mjs does.
// Robots keep their native size (hand-drawn, not pixel art). NUDGE moves a
// robot after the mapping, to clear the card or a neighbour.
//
//   node tools/art/retro-freed-layout.mjs [--check] [--preview out.png [--count N]]
import fs from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";
import { composite, decodePng, encodePng } from "./lib/png.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = path.join(root, "js/skins/retro-robots.js");
const BACKGROUND = "retro/victory-bg.png";

// 8a9315e:EndLevelRobots.js, verbatim: [image, x, y (sprite centre), z]
const ORIGINAL = [
  ["myrobo.png", 520, 425, 3], ["aibo.png", 610, 510, 3], ["mechagodzilla.png", 224, 276, 0],
  ["securiton.png", 900, 381, 2], ["asimo.png", 700, 426, 7], ["turret.png", 355, 568, 5],
  ["bender.png", 236, 415, 3], ["dalek.png", 80, 412, 2], ["marsrover.png", 786, 527, 4],
  ["cylon.png", 676, 348, 7], ["r2d2.png", 200, 652, 6], ["awesomo.png", 910, 628, 4],
  ["tachikoma.png", 148, 366, 1], ["pris.png", 590, 374, 1], ["scv.png", 886, 480, 3],
  ["lostinspacerobot.png", 320, 350, 2], ["claptrap.png", 460, 560, 5], ["wheatley.png", 420, 670, 6],
  ["kitt.png", 530, 337, 0], ["marvin.png", 800, 640, 6], ["partyrock.png", 420, 325, 0],
  ["robotchicken.png", 625, 665, 6], ["sojourner.png", 300, 504, 4], ["roomba.png", 320, 673, 7],
  ["wall-e.png", 640, 578, 4], ["Canti.png", 382, 435, 3], ["jetsons.png", 112, 556, 6],
  ["ed209.png", 800, 370, 1], ["crowtrobot.png", 80, 660, 7], ["geth.png", 447, 400, 1],
  ["optimusPrime.png", 926, 287, 0], ["eve.png", 960, 560, 4], ["darpadog.png", 620, 430, 2],
];
const FEET_2012 = [377, 760];
const GROUND_TOP = 528, GROUND_BOTTOM = 762;
const NUDGE = { // image -> {dx, dy}: clear robots the mapping buried
  "kitt.png": { dx: -10, dy: 224 }, // the car was hidden behind the main robot (as in 2012); park it in the front gap
  "marsrover.png": { dx: -46, dy: -24 },
  "partyrock.png": { dx: -14, dy: -18 },
  "mechagodzilla.png": { dx: -60, dy: 40 }, // its head was under the desktop result card (x 214-809, y < 380)
};

const pngSize = (file) => {
  const b = fs.readFileSync(file);
  return { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
};

const rows = ORIGINAL.map(([name, x0, y0], i) => {
  const { w, h } = pngSize(path.join(root, "images/retro/robots", name));
  const feet0 = y0 + h / 2;
  const k = (GROUND_BOTTOM - GROUND_TOP) / (FEET_2012[1] - FEET_2012[0]);
  const n = NUDGE[name] ?? {};
  const feet = Math.round(GROUND_TOP + (feet0 - FEET_2012[0]) * k) + (n.dy ?? 0);
  const x = x0 + (n.dx ?? 0);
  const y = Math.round(feet - h / 2);
  const z = Math.max(1, Math.round((feet - 480) / 10));
  return { name, i, x, y, z, w, h };
});

const pad = (s, n) => s.padEnd(n);
const lines = rows.map((r) => `  [${pad(`"retro/robots/${r.name}",`, 39)}${String(r.x).padStart(4)}, ${String(r.y).padStart(3)}, ${String(r.z).padStart(2)}, ${String(r.w).padStart(3)}, ${String(r.h).padStart(3)}]${r.i === rows.length - 1 ? " " : ","} // ${r.i === 0 ? "main robot, always shown" : `freed at ${3 * r.i} points`}`);
const js = `// Retro skin end-level crowd (bead tg-wtv.3): the user's hand-drawn 2012
// robots on the phosphor-green night backdrop. Read by js/scenes/end-level.js
// when t.Skin.id is "retro"; same unlock order and rules as EndLevelRobots.js
// (entry 0 always shown, entry i freed at 3*i points). Each entry is
// [image, x, y, z, w, h]: x/y the sprite centre in the 1024x768 landscape,
// z the draw order, w/h the native size (these images are not in the
// preloader, so the scene cannot ask Q.asset for their size).
// Generated by node tools/art/retro-freed-layout.mjs (2012 layout from
// git show 8a9315e:EndLevelRobots.js, feet mapped onto the backdrop's ground).
t.EndLevelRobotsRetro = {
	background: "${BACKGROUND}",
	data: [ // image, x, y, z, w, h
${lines.join("\n")}
	]
};
`;

const args = process.argv.slice(2);
if (args.includes("--check")) {
  const ok = fs.existsSync(OUT) && fs.readFileSync(OUT, "utf8") === js;
  console.log(ok ? "ok: js/skins/retro-robots.js is current" : "FAIL js/skins/retro-robots.js is stale: run node tools/art/retro-freed-layout.mjs");
  process.exit(ok ? 0 : 1);
}
const previewAt = args.indexOf("--preview");
if (previewAt >= 0) {
  const out = args[previewAt + 1];
  const countAt = args.indexOf("--count");
  const count = countAt >= 0 ? Number(args[countAt + 1]) : rows.length;
  const bg = decodePng(fs.readFileSync(path.join(root, "images", BACKGROUND)));
  const items = rows.slice(0, count).sort((a, b) => a.z - b.z || a.i - b.i);
  for (const r of items) composite(bg, decodePng(fs.readFileSync(path.join(root, "images/retro/robots", r.name))), Math.round(r.x - r.w / 2), Math.round(r.y - r.h / 2));
  fs.writeFileSync(out, encodePng(bg));
  console.log(`wrote ${out}: ${items.length} robot(s)`);
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, js);
  console.log(`wrote ${path.relative(root, OUT)}: ${rows.length} robots`);
}
